const req=createRequire('C:/Users/luigi/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/_hub_require.cjs');
const {chromium}=req('playwright');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launchPersistentContext(path.resolve(__dirname,'../.qa-browser-profile'),{headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--disable-gpu','--disable-crash-reporter'],viewport:{width:1500,height:1000}});
 const page=await browser.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(pathToFileURL(path.resolve(__dirname,'../preview.html')).href);
 await page.waitForFunction(()=>document.querySelectorAll('.layer-image').length===34 && [...document.querySelectorAll('.layer-image')].every(x=>x.complete&&x.naturalWidth>0));
 assert.equal(await page.locator('.layer-image').count(),34);
 await page.getByRole('button',{name:/Dije Fearless/}).click();
 await page.locator('#solo').click();
 assert.equal(await page.locator('.layer-image:not([hidden])').count(),1);
 await page.locator('#show-all').click();
 assert.equal(await page.locator('.layer-image:not([hidden])').count(),34);
 await page.getByRole('button',{name:'Comparar',exact:true}).click();
 await page.locator('#compare-range').fill('40');
 assert.equal(await page.locator('#original').isVisible(),true);
 await page.getByRole('button',{name:'Capas',exact:true}).click();
 await page.locator('#animate').check();
 assert.equal(await page.locator('#stage').evaluate(x=>x.classList.contains('is-animating')),true);
 await page.locator('#animate').uncheck();
 await page.locator('#transparency').uncheck();
 await page.locator('#show-bounds').uncheck();
 await page.screenshot({path:path.resolve(__dirname,'../viewer-preview.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 await page.setViewportSize({width:700,height:900});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 assert.equal(overflow,false);
 await browser.close();
 console.log('PASS: 34 assets loaded; solo/show-all; comparison; animation; no JS errors; responsive width.');
})().catch(e=>{console.error(e);process.exitCode=1;});
